function chapter(
  title: string,
  lead: string,
  sections: ChapterSection[],
  evidence: ReadingEvidence[],
): Chapter {
  return {
    title,
    lead,
    sections,
    body: [lead, ...sections.map((s) => s.body)].join("\n\n"),
    evidence,
    question: "이 장면에서 실제 내 모습과 닮은 부분, 달랐던 부분은 무엇인가요?",
  };
}

